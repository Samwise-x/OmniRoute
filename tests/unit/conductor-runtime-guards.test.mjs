test(
  "Faro enforces bearer auth, input bounds and degraded readiness",
  { timeout: 30000 },
  async () => {
    const dir = await mkdtemp(path.join(os.tmpdir(), "omni-conductor-faro-guards-"));
    const hubPort = await freePort();
    const faroPort = await freePort();
    const hubUrl = `http://127.0.0.1:${hubPort}`;
    const faroUrl = `http://127.0.0.1:${faroPort}`;
    let hub, faro;
    try {
      faro = start("services/omni-conductor/faro.mjs", {
        HOST: "127.0.0.1",
        PORT: String(faroPort),
        CONDUCTOR_HUB_URL: hubUrl,
        CONDUCTOR_HUB_TOKEN: TOKEN,
      });
      // No Hub yet: readiness must report degraded, not crash or report ok.
      for (let i = 0; i < 150; i++) {
        try {
          const probe = await fetch(`${faroUrl}/readyz`);
          assert.equal(probe.status, 503);
          assert.equal((await probe.json()).status, "degraded");
          break;
        } catch {
          await wait(40);
        }
      }
      hub = start("services/omni-conductor/hub.mjs", {
        HOST: "127.0.0.1",
        PORT: String(hubPort),
        CONDUCTOR_HUB_TOKEN: TOKEN,
        CONDUCTOR_STATE_FILE: path.join(dir, "state.json"),
      });
      await healthy(`${hubUrl}/health`, hub);
      await healthy(`${faroUrl}/health`, faro);

      assert.equal((await fetch(`${faroUrl}/ask`, { method: "POST" })).status, 401);
      assert.equal(
        (
          await fetch(`${faroUrl}/ask`, {
            method: "POST",
            headers: { authorization: "Bearer nope", "content-type": "application/json" },
            body: JSON.stringify({ message: "hi" }),
          })
        ).status,
        401
      );
      assert.equal((await api(faroUrl, "/nope", { message: "x" })).status, 404);
      assert.equal((await api(faroUrl, "/ask", { message: "" })).status, 400);
      assert.equal((await api(faroUrl, "/ask", { message: "x".repeat(4_001) })).status, 400);
      assert.equal(
        (await api(faroUrl, "/ask", { message: "hi", confirmation_token: { not: "a string" } }))
          .status,
        400
      );

      // Deterministic, evidence-grounded answers — no model configured.
      const fleetAnswer = await (
        await api(faroUrl, "/ask", { message: "which runners are online?" })
      ).json();
      assert.equal(fleetAnswer.pending, null);
      assert.match(fleetAnswer.text, /0 available runner/);
      const emptyAnswer = await (await api(faroUrl, "/ask", { message: "list the tasks" })).json();
      assert.match(emptyAnswer.text, /no tasks to report/);
      const unknownAnswer = await (
        await api(faroUrl, "/ask", { message: "what about task_deadbeef?" })
      ).json();
      assert.match(unknownAnswer.text, /was not found/);

      // A no-op confirmation and an already-terminal cancellation never act.
      assert.match(
        (await (await api(faroUrl, "/ask", { message: "no" })).json()).text,
        /No action was taken/
      );
      assert.match(
        (await (await api(faroUrl, "/ask", { message: "yes" })).json()).text,
        /No valid, unexpired action/
      );

      // Creation requires HTTPS + an explicit confirmation round-trip.
      const insecure = await (
        await api(faroUrl, "/ask", { message: "create task http://x.example/r.git | hi" })
      ).json();
      assert.equal(insecure.pending, null);
      const proposed = await (
        await api(faroUrl, "/ask", { message: "create task https://x.example/r.git | add docs" })
      ).json();
      assert.equal(proposed.pending.action, "create_task");
      assert.ok(proposed.pending.token);

      const created = await (
        await api(faroUrl, "/ask", { message: "yes", confirmation_token: proposed.pending.token })
      ).json();
      const taskId = created.text.match(/task_[\w-]+/)[0];
      const replay = await (
        await api(faroUrl, "/ask", { message: "yes", confirmation_token: proposed.pending.token })
      ).json();
      assert.match(replay.text, new RegExp(taskId), "replaying a confirmation must be idempotent");

      const cancel = await (await api(faroUrl, "/ask", { message: `cancel ${taskId}` })).json();
      assert.equal(cancel.pending.action, "cancel_task");
      const canceled = await (
        await api(faroUrl, "/ask", { message: "yes", confirmation_token: cancel.pending.token })
      ).json();
      assert.match(canceled.text, /is canceled in Hub/);
      const again = await (await api(faroUrl, "/ask", { message: `cancel ${taskId}` })).json();
      assert.equal(again.pending, null);
      assert.match(again.text, /already canceled|no action was taken/i);
    } finally {
      if (faro) await stop(faro);
      if (hub) await stop(hub);
      await rm(dir, { recursive: true, force: true });
    }
  }
);

test("Faro surfaces the Hub's own evidence for a completed task", { timeout: 45000 }, async () => {
  const dir = await mkdtemp(path.join(os.tmpdir(), "omni-conductor-faro-evidence-"));
  const { url, hub, runner } = await startFleet(dir);
  let faro;
  const faroPort = await freePort();
  const faroUrl = `http://127.0.0.1:${faroPort}`;
  try {
    const repo = await makeRepo(dir);
    const task = await submitAndAwait(url, `file://${repo}`);
    assert.equal(task.status, "completed", runner.logs);

    faro = start("services/omni-conductor/faro.mjs", {
      HOST: "127.0.0.1",
      PORT: String(faroPort),
      CONDUCTOR_HUB_URL: url,
      CONDUCTOR_HUB_TOKEN: TOKEN,
    });
    await healthy(`${faroUrl}/health`, faro);

    const answer = await (
      await api(faroUrl, "/ask", { message: `what happened to ${task.id}?` })
    ).json();
    assert.match(answer.text, new RegExp(task.id));
    assert.match(answer.text, /completed/);
    assert.match(answer.text, /guard-runner/);
    assert.match(answer.text, /Tests: skipped/);
    // Evidence only: Faro must not claim an action it did not take.
    assert.equal(answer.pending, null);
  } finally {
    if (faro) await stop(faro);
    await stop(runner);
    await stop(hub);
    await rm(dir, { recursive: true, force: true });
  }
});
