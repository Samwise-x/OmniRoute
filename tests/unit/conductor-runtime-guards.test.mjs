/**
 * OmniConductor runtime guards — the *rejection* half of the v1 contract.
 *
 * The happy path lives in `conductor-runtime.test.mjs` (Hub → Runners → repository
 * tests → patch). This file drives the same three real service processes against
 * the paths an operator actually depends on when things go wrong, because those
 * are the paths where a silent regression is indistinguishable from "no task was
 * submitted":
 *
 *   - Runner refuses repositories that are not public HTTPS (no scheme, embedded
 *     credentials, loopback/private resolution, host not in the allowlist) BEFORE
 *     any clone happens — the SSRF/credential-exfiltration boundary.
 *   - Runner reports a malformed `RUNNER_TEST_COMMAND` and a failing repository
 *     test as task failures with the command and exit code attached, instead of
 *     quietly reporting a green task.
 *   - Hub rejects malformed JSON and keeps its documented 401/404 shapes.
 *   - Faro enforces bearer auth, input bounds, and its degraded-readiness signal,
 *     and its deterministic answers stay grounded in Hub evidence.
 *
 * Every assertion below is made against a process started with `spawn`, not a
 * mock: no API key and no external model is used.
 */
import test from "node:test";
import assert from "node:assert/strict";
import { spawn, execFileSync } from "node:child_process";
import { mkdtemp, mkdir, writeFile, chmod, rm } from "node:fs/promises";
import { createServer } from "node:http";
import os from "node:os";
import path from "node:path";
import { once } from "node:events";

const ROOT = path.resolve(import.meta.dirname, "../..");
const TOKEN = "omni-conductor-guards-token-0123456789";
const wait = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

async function freePort() {
  const server = createServer();
  server.listen(0, "127.0.0.1");
  await once(server, "listening");
  const port = server.address().port;
  server.close();
  await once(server, "close");
  return port;
}

function start(script, env) {
  const child = spawn(process.execPath, [script], {
    cwd: ROOT,
    env: { ...process.env, ...env },
    stdio: ["ignore", "pipe", "pipe"],
  });
  child.logs = "";
  child.stdout.on("data", (data) => (child.logs += data));
  child.stderr.on("data", (data) => (child.logs += data));
  return child;
}

async function stop(child) {
  if (!child || child.exitCode !== null) return;
  child.kill("SIGTERM");
  await Promise.race([once(child, "exit"), wait(3000)]);
  if (child.exitCode === null) child.kill("SIGKILL");
}

async function healthy(url, child) {
  for (let i = 0; i < 150; i++) {
    if (child.exitCode !== null) throw new Error(`service exited: ${child.logs}`);
    try {
      if ((await fetch(url)).ok) return;
    } catch {}
    await wait(40);
  }
  throw new Error(`service did not become healthy: ${child.logs}`);
}

const api = (base, route, body, method = "POST", headers = {}) =>
  fetch(`${base}${route}`, {
    method,
    headers: { authorization: `Bearer ${TOKEN}`, "content-type": "application/json", ...headers },
    ...(body === undefined ? {} : { body: JSON.stringify(body) }),
  });

async function awaitTask(base, id, terminals = ["completed", "failed", "canceled"]) {
  for (let i = 0; i < 250; i++) {
    const task = await (await api(base, `/v1/tasks/${id}`, undefined, "GET")).json();
    if (terminals.includes(task.status)) return task;
    await wait(35);
  }
  throw new Error(`task ${id} did not become terminal`);
}

/** A disposable git repository. Refusals happen BEFORE the clone, so the
 * admission-boundary cases never touch it — it exists for the tests that need a
 * clone to succeed (test evidence, readiness, Faro answers). */
async function makeRepo(dir) {
  const repo = path.join(dir, "repo");
  await mkdir(repo);
  execFileSync("git", ["init", "-b", "main"], { cwd: repo });
  execFileSync("git", ["config", "user.email", "guard-test@example.invalid"], { cwd: repo });
  execFileSync("git", ["config", "user.name", "OmniConductor guard test"], { cwd: repo });
  await writeFile(path.join(repo, "README.md"), "fixture\n");
  execFileSync("git", ["add", "."], { cwd: repo });
  execFileSync("git", ["commit", "-m", "fixture"], { cwd: repo });
  return repo;
}

/** A Gateway-compatible adapter: writes a file and prints its argv. */
async function makeGateway(dir, { exitCode = 0, body = "" } = {}) {
  const file = path.join(dir, "guard-gateway.mjs");
  await writeFile(
    file,
    `#!/usr/bin/env node\n` +
      `import fs from 'node:fs';\n` +
      `const a = process.argv.slice(2);\n` +
      `const repo = a[a.indexOf('--repo') + 1];\n` +
      `const prompt = a[a.indexOf('--prompt') + 1];\n` +
      `${body}\n` +
      `if (repo && prompt !== 'touch-nothing') fs.writeFileSync(repo + '/generated.txt', 'generated by runner\\n');\n` +
      `console.log('guard-gateway done');\n` +
      `process.exit(${exitCode});\n`
  );
  await chmod(file, 0o755);
  return file;
}

/** Bootstrap: one Hub + one Runner, returning the handles a test must clean up. */
async function startFleet(dir, extraRunnerEnv = {}) {
  const hubPort = await freePort();
  const url = `http://127.0.0.1:${hubPort}`;
  const hub = start("services/omni-conductor/hub.mjs", {
    HOST: "127.0.0.1",
    PORT: String(hubPort),
    CONDUCTOR_HUB_TOKEN: TOKEN,
    CONDUCTOR_STATE_FILE: path.join(dir, "state.json"),
  });
  await healthy(`${url}/health`, hub);
  const gateway = await makeGateway(dir);
  const healthPort = await freePort();
  const runner = start("services/omni-conductor/runner.mjs", {
    CONDUCTOR_HUB_URL: url,
    CONDUCTOR_HUB_TOKEN: TOKEN,
    RUNNER_ID: "guard-runner",
    RUNNER_HEALTH_HOST: "127.0.0.1",
    RUNNER_HEALTH_PORT: String(healthPort),
    RUNNER_CLIS: "gateway",
    RUNNER_MODELS: "*",
    GATEWAY_BIN: gateway,
    RUNNER_ALLOW_LOCAL_REPOS: "true",
    RUNNER_MAX_CONCURRENCY: "1",
    RUNNER_POLL_MS: "40",
    RUNNER_TASK_TIMEOUT_MS: "8000",
    RUNNER_TEST_TIMEOUT_MS: "20000",
    ...extraRunnerEnv,
  });
  for (let i = 0; i < 150; i++) {
    if (runner.exitCode !== null) throw new Error(`runner exited: ${runner.logs}`);
    const fleet = await (await api(url, "/v1/runners", undefined, "GET")).json();
    if (fleet.some((r) => r.id === "guard-runner" && r.online)) break;
    await wait(40);
  }
  return { url, hub, runner, healthPort };
}

async function submitAndAwait(url, repoUrl, prompt = "do the work") {
  const created = await api(url, "/v1/tasks", { repo: { url: repoUrl }, spec: { prompt } });
  assert.equal(created.status, 201, await created.clone().text());
  const { id } = await created.json();
  return awaitTask(url, id);
}

