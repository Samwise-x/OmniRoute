test(
  "Runner refuses every non-public-HTTPS repository shape before cloning",
  { timeout: 60000 },
  async () => {
    const dir = await mkdtemp(path.join(os.tmpdir(), "omni-conductor-admission-"));
    const { url, hub, runner } = await (async () => {
      const fleet = await startFleet(dir);
      return fleet;
    })();
    try {
      await makeRepo(dir);
      // `RUNNER_ALLOW_LOCAL_REPOS` stays on, so `file://` remains the one allowed
      // non-network scheme — everything below must still be refused.
      const cases = [
        { repo: "https://user:pass@github.com/acme/repo.git", why: /not permitted/ },
        { repo: "https://localhost/acme/repo.git", why: /not permitted/ },
        { repo: "https://127.0.0.1/acme/repo.git", why: /not permitted/ },
        { repo: "https://10.1.2.3/acme/repo.git", why: /not permitted/ },
        { repo: "https://192.168.4.5/acme/repo.git", why: /not permitted/ },
        { repo: "https://169.254.169.254/latest/meta-data.git", why: /not permitted/ },
        { repo: "https://[::1]/acme/repo.git", why: /not permitted/ },
        { repo: "https://nothing-resolves.invalid/acme/repo.git", why: /not permitted/ },
        { repo: "http://github.com/acme/repo.git", why: /not permitted/ },
        { repo: "ssh://git@github.com/acme/repo.git", why: /not permitted/ },
        { repo: "not-a-url", why: /HTTPS git URL/ },
      ];
      for (const { repo, why } of cases) {
        const task = await submitAndAwait(url, repo, "inspect argv");
        assert.equal(task.status, "failed", `${repo} should be refused: ${runner.logs}`);
        assert.match(task.manifest.error, why, `${repo} produced: ${task.manifest.error}`);
        assert.equal(task.manifest.tests.status, "not_run");
        // Refusal happens before the harness ever runs.
        assert.equal(task.manifest.result?.output, undefined);
      }
    } finally {
      await stop(runner);
      await stop(hub);
      await rm(dir, { recursive: true, force: true });
    }
  }
);

