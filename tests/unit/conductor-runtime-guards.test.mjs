test(
  "Hub rejects malformed bodies and unknown routes with its documented shapes",
  { timeout: 20000 },
  async () => {
    const dir = await mkdtemp(path.join(os.tmpdir(), "omni-conductor-hub-errors-"));
    const port = await freePort();
    const url = `http://127.0.0.1:${port}`;
    const hub = start("services/omni-conductor/hub.mjs", {
      HOST: "127.0.0.1",
      PORT: String(port),
      CONDUCTOR_HUB_TOKEN: TOKEN,
      CONDUCTOR_STATE_FILE: path.join(dir, "state.json"),
    });
    try {
      await healthy(`${url}/health`, hub);
      // Health is deliberately anonymous (Compose probes it without a token).
      const anonHealth = await fetch(`${url}/health`);
      assert.equal(anonHealth.status, 200);
      assert.equal((await anonHealth.json()).service, "omni-conductor-hub");
      // Everything else is bearer-only.
      for (const route of ["/v1/tasks", "/v1/runners", "/v1/events"]) {
        assert.equal((await fetch(`${url}${route}`)).status, 401, route);
        assert.equal(
          (
            await fetch(`${url}${route}`, {
              headers: { authorization: "Bearer wrong-token-wrong" },
            })
          ).status,
          401,
          route
        );
      }
      // Malformed JSON is a 400 from the handler's catch, not a 500 or a hang.
      const badJson = await fetch(`${url}/v1/tasks`, {
        method: "POST",
        headers: { authorization: `Bearer ${TOKEN}`, "content-type": "application/json" },
        body: '{"repo": ',
      });
      assert.equal(badJson.status, 400);
      assert.deepEqual(await badJson.json(), { error: "invalid request" });

      // Validation messages are explicit about the missing field.
      const missingPrompt = await api(url, "/v1/tasks", {
        repo: { url: "https://x.example/r.git" },
      });
      assert.equal(missingPrompt.status, 400);
      assert.match((await missingPrompt.json()).error, /spec\.prompt/);

      const oversized = await api(url, "/v1/tasks", {
        repo: { url: "https://x.example/r.git" },
        spec: { prompt: "p".repeat(40_001) },
      });
      assert.equal(oversized.status, 413);

      // Bad runner registrations are refused instead of poisoning the fleet.
      for (const bad of [
        { id: "bad id", capabilities: { clis: [] } },
        { id: "ok", capabilities: {} },
        { capabilities: { clis: [] } },
      ]) {
        assert.equal((await api(url, "/v1/runners/register", bad)).status, 400);
      }
      const fleet = await (await api(url, "/v1/runners", undefined, "GET")).json();
      assert.deepEqual(fleet, []);

      assert.equal((await api(url, "/v1/tasks/task_missing", undefined, "GET")).status, 404);
      assert.equal((await api(url, "/v1/tasks/task_missing/cancel", {})).status, 404);
      assert.equal((await api(url, "/v1/runner/claim", { id: "ghost" })).status, 404);
      assert.equal((await api(url, "/v1/runners/heartbeat", { id: "ghost" })).status, 404);
      assert.equal((await api(url, "/nope", {})).status, 404);
    } finally {
      await stop(hub);
      await rm(dir, { recursive: true, force: true });
    }
  }
);

